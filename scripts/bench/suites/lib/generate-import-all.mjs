/**
 * Generates a synthetic node:test file that imports every eligible source
 * file once, so Node's `--experimental-test-coverage` / lcov reporter has an
 * `SF:` entry for files no real test transitively imports — otherwise those
 * files are silently ABSENT from the coverage report rather than reported at
 * 0% (verified experimentally: `--test-coverage-include` only restricts
 * which of the files a test run actually LOADED are reported; it does not
 * force-include an unloaded file). This is how "include-all" coverage in
 * this repo is achieved — see config/benchmarks/coverage.json.
 *
 * A per-file import failure is caught and recorded, never thrown — one
 * unimportable module (e.g. one that touches `window` at module scope) must
 * not abort the whole coverage run or blank out every other file's numbers.
 */

import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";

/**
 * @param {string[]} repoRelativeFiles
 * @param {string} outTestFilePath - where to write the generated .mjs test file
 * @param {string} failuresOutPath - where the generated test writes its JSON failure list
 */
export function writeImportAllTestFile(repoRelativeFiles, outTestFilePath, failuresOutPath) {
  const fileUrls = repoRelativeFiles.map((f) => ({
    repoPath: f,
    url: pathToFileURL(resolve(process.cwd(), f)).href,
  }));

  const entries = fileUrls
    .map(({ repoPath, url }) => `  { repoPath: ${JSON.stringify(repoPath)}, url: ${JSON.stringify(url)} },`)
    .join("\n");

  const content = `// GENERATED by scripts/bench/suites/lib/generate-import-all.mjs — do not edit, not committed.
import { test } from "node:test";
import { writeFileSync } from "node:fs";

const FILES = [
${entries}
];
const FAILURES_OUT = ${JSON.stringify(failuresOutPath)};

test("bench:coverage import-all (denominator only, not a real test)", async (t) => {
  const failures = [];
  for (const { repoPath, url } of FILES) {
    await t.test(repoPath, async () => {
      try {
        await import(url);
      } catch (error) {
        failures.push({ file: repoPath, error: error instanceof Error ? error.message : String(error) });
      }
    });
  }
  writeFileSync(FAILURES_OUT, JSON.stringify(failures, null, 2));
});
`;

  writeFileSync(outTestFilePath, content);
}
