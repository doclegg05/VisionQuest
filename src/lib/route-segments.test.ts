import assert from "node:assert/strict";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { describe, it } from "node:test";

// H1 privacy follow-up, item 7 (2026-11-10). An error report names a route by
// its pattern, and `routePattern` (src/lib/sentry-scrub.ts) keeps a path
// segment only when it is the name of a real route directory. That list is
// generated here from src/app and checked in, so the browser can ship it
// without reading the disk. This test fails when a route directory is added
// or removed and the list was not regenerated:
//
//   UPDATE_ROUTE_SEGMENTS=1 node --import tsx --test src/lib/route-segments.test.ts

const APP_DIR = path.join(process.cwd(), "src", "app");
const GENERATED = path.join(process.cwd(), "src", "lib", "route-segments.generated.ts");
const REGENERATE = "UPDATE_ROUTE_SEGMENTS=1 node --import tsx --test src/lib/route-segments.test.ts";

/**
 * Every directory name under src/app. Private folders (`_name`) and parallel
 * route slots (`@name`) are left out with everything below them: no URL and
 * no route pattern contains one.
 */
function directoryNames(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !/^[_@]/.test(entry.name))
    .flatMap((entry) => [entry.name, ...directoryNames(path.join(dir, entry.name))]);
}

function renderModule(names: readonly string[]): string {
  return [
    "// Generated by src/lib/route-segments.test.ts from the directory names under",
    "// src/app. Do not edit by hand. To regenerate:",
    `//   ${REGENERATE}`,
    "export const ROUTE_SEGMENTS: readonly string[] = [",
    ...names.map((name) => `  ${JSON.stringify(name)},`),
    "];",
    "",
  ].join("\n");
}

describe("route segment list", () => {
  it("matches the directories under src/app", () => {
    const expected = renderModule([...new Set(directoryNames(APP_DIR))].sort());
    if (process.env.UPDATE_ROUTE_SEGMENTS === "1") writeFileSync(GENERATED, expected);
    const actual = existsSync(GENERATED) ? readFileSync(GENERATED, "utf8") : "";
    assert.equal(actual, expected, `src/lib/route-segments.generated.ts is stale. Regenerate it: ${REGENERATE}`);
  });

  it("holds real route names and no private folder", () => {
    const names = [...new Set(directoryNames(APP_DIR))];
    for (const name of ["api", "teacher", "credentials", "[id]", "(student)"]) {
      assert.ok(names.includes(name), `${name} is missing`);
    }
    assert.ok(!names.some((name) => name.startsWith("_")), "a private folder is in the list");
  });
});
